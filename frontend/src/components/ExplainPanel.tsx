import { useCallback, useEffect, useRef, useState } from "react";
import { api, friendlyMessage, isApiError } from "../api/client";
import type { ExplainResponse, LabelAttribution } from "../api/types";
import { formatModelScore } from "../utils/modelScore";
import { useApp } from "../AppContext";
import { btn, disclosure, disclosureSummary, msg, panel, panelTitle, scoreValue, spinner } from "../ui";

export interface ExplainPanelProps {
  captureId: string;
  runId?: string | null;
  positive?: string[];
  blind?: boolean;
  autoGenerate?: boolean;
}

export default function ExplainPanel({
  captureId,
  runId,
  positive = [],
  blind = false,
  autoGenerate = false,
}: ExplainPanelProps) {
  const { config } = useApp();
  const hasFindings = positive.length > 0;
  const displayNames = config?.active_model.display_names ?? {};
  const enabled =
    !!config?.explain?.enabled && config.explain.methods.includes("gradcam");

  const [current, setCurrent] = useState<ExplainResponse | null>(null);
  const [showOverlay, setShowOverlay] = useState(true);
  const [busy, setBusy] = useState(false);
  const [elapsed, setElapsed] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const autoGeneratedFor = useRef<string | null>(null);

  // Viewing history is read-only: show the map generated during the original
  // run (or, failing that, the newest current one) and never compute another.
  const [loaded, setLoaded] = useState(false);
  useEffect(() => {
    if (autoGenerate || blind || !enabled) return;
    let cancelled = false;
    setLoaded(false);
    void (async () => {
      try {
        const runs = (await api.listExplanations(captureId)).explanations.filter(
          (run) => run.method === "gradcam" && !run.stale
        );
        const pick =
          runs.find((run) => runId != null && run.run_id === runId) ?? runs[0];
        const result = pick
          ? await api.getExplanation(captureId, pick.explain_id)
          : null;
        if (!cancelled) setCurrent(result);
      } catch (e) {
        if (!cancelled)
          setError(isApiError(e) ? friendlyMessage(e.code, e.message) : String(e));
      } finally {
        if (!cancelled) setLoaded(true);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, [autoGenerate, blind, captureId, enabled, runId]);

  const timer = useRef<number | null>(null);
  useEffect(() => {
    if (!busy) {
      if (timer.current) window.clearInterval(timer.current);
      timer.current = null;
      return;
    }
    setElapsed(0);
    timer.current = window.setInterval(
      () => setElapsed((value) => value + 1),
      1000
    );
    return () => {
      if (timer.current) window.clearInterval(timer.current);
    };
  }, [busy]);

  const runGradCam = useCallback(async () => {
    setBusy(true);
    setError(null);
    try {
      const result = await api.explain(captureId, {
        method: "gradcam",
        labels: positive,
        run_id: runId ?? null,
      });
      setCurrent(result);
    } catch (e) {
      setError(isApiError(e) ? friendlyMessage(e.code, e.message) : String(e));
    } finally {
      setBusy(false);
    }
  }, [captureId, positive, runId]);

  useEffect(() => {
    // Grad-CAM explains predicted findings only: a label below its threshold
    // gets no map, so a run with no positive label generates nothing.
    if (!autoGenerate || blind || !enabled || !hasFindings) return;
    const resultKey = `${captureId}:${runId ?? "latest"}`;
    if (autoGeneratedFor.current === resultKey) return;
    autoGeneratedFor.current = resultKey;
    // A reloaded result page already has its map on disk: reopen it instead
    // of recomputing and storing a duplicate.
    void (async () => {
      try {
        const existing = (await api.listExplanations(captureId)).explanations.find(
          (run) =>
            run.method === "gradcam" && !run.stale && runId != null && run.run_id === runId
        );
        if (existing) {
          setCurrent(await api.getExplanation(captureId, existing.explain_id));
          return;
        }
      } catch {
        // Listing is best-effort; fall through to generating a fresh map.
      }
      await runGradCam();
    })();
  }, [autoGenerate, blind, captureId, enabled, hasFindings, runGradCam, runId]);

  if (!enabled) return null;

  return (
    <div className={`${panel} mb-4.5 print:break-inside-avoid`}>
      <div className="flex items-center justify-between gap-3 flex-wrap mb-1">
        <h2 className={`${panelTitle} mt-0 mx-0`}>Grad-CAM</h2>
        {!blind && autoGenerate && busy ? (
          <span className="text-ink-muted text-[0.82rem] whitespace-nowrap print:hidden" aria-live="polite">
            <span className={`${spinner} size-3.5 border-2 mr-1.25 align-[-2px]`} />
            Generating heatmaps… {elapsed}s
          </span>
        ) : null}
      </div>

      {blind ? <p className="text-ink-muted text-[0.85rem] mt-2 mx-0 mb-0">Available after labels are entered.</p> : null}
      {error ? <div className={`${msg.error} mt-3`}>{error}</div> : null}

      {autoGenerate && !blind && !hasFindings ? (
        <p className="text-ink-muted text-[0.85rem] mt-2 mx-0 mb-0">No finding crossed its threshold, so no Grad-CAM map was generated.</p>
      ) : null}

      {!autoGenerate && !blind && loaded && !current && !error ? (
        <p className="text-ink-muted text-[0.85rem] mt-2 mx-0 mb-0">No Grad-CAM map was generated for this capture.</p>
      ) : null}

      {!blind && current ? (
        <GradCamResult
          result={current}
          displayNames={displayNames}
          showOverlay={showOverlay}
          onToggleOverlay={() => setShowOverlay((value) => !value)}
        />
      ) : null}
    </div>
  );
}

function GradCamResult({
  result,
  displayNames,
  showOverlay,
  onToggleOverlay,
}: {
  result: ExplainResponse;
  displayNames: Record<string, string>;
  showOverlay: boolean;
  onToggleOverlay: () => void;
}) {
  const positiveAttributions = result.attributions.filter(
    (attribution) => attribution.positive !== false
  );
  const negativeAttributions = result.attributions.filter(
    (attribution) => attribution.positive === false
  );

  return (
    <div className="mt-4.5 border-t border-line pt-3.5">
      <div className="flex items-center justify-between gap-2.5 flex-wrap mb-2.5 print:hidden">
        <span className="text-ink-muted">{showOverlay ? "Overlay" : "Heatmap"}</span>
        <button type="button" className={`${btn.small} ${btn.ghost}`} onClick={onToggleOverlay}>
          {showOverlay ? "Show heatmap" : "Show overlay"}
        </button>
      </div>
      <AttributionGrid
        attributions={positiveAttributions}
        displayNames={displayNames}
        showOverlay={showOverlay}
      />
      {negativeAttributions.length ? (
        <details className={`${disclosure} print:hidden`}>
          <summary className={disclosureSummary}>Negative maps ({negativeAttributions.length})</summary>
          <div className="mt-3">
            <AttributionGrid
              attributions={negativeAttributions}
              displayNames={displayNames}
              showOverlay={showOverlay}
            />
          </div>
        </details>
      ) : null}
    </div>
  );
}

function AttributionGrid({
  attributions,
  displayNames,
  showOverlay,
}: {
  attributions: LabelAttribution[];
  displayNames: Record<string, string>;
  showOverlay: boolean;
}) {
  return (
    <div className="grid grid-cols-[repeat(auto-fit,minmax(260px,1fr))] gap-3 print:grid-cols-2">
      {attributions.map((attribution) => (
        <AttributionCard
          key={attribution.label}
          attribution={attribution}
          displayName={displayNames[attribution.label] ?? attribution.label}
          showOverlay={showOverlay}
        />
      ))}
    </div>
  );
}

function AttributionCard({
  attribution,
  displayName,
  showOverlay,
}: {
  attribution: LabelAttribution;
  displayName: string;
  showOverlay: boolean;
}) {
  const url = showOverlay
    ? attribution.files.overlay
    : attribution.files.heatmap;
  return (
    <figure className="m-0 bg-panel-2 border border-line rounded-control overflow-hidden print:break-inside-avoid">
      {url ? (
        <img className="block w-full h-auto bg-canvas-soft" src={url} alt={`${displayName} Grad-CAM`} loading="lazy" />
      ) : null}
      <figcaption className="flex items-center justify-between gap-2 mb-0 pt-2 px-2.5 pb-2.5">
        <span className="font-semibold text-[0.9rem]">{displayName}</span>
        {typeof attribution.score === "number" ? (
          <span className="flex items-baseline gap-1.5 flex-none">
            <small className="text-ink-muted text-[0.68rem]">Model score</small>
            <strong className={`${scoreValue} text-[1.1rem]`}>
              {formatModelScore(attribution.score)}
            </strong>
          </span>
        ) : null}
      </figcaption>
    </figure>
  );
}
